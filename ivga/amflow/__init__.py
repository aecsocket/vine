type ValueLike = Value | ValueCastable | Enum | int

class Flow:
  def __init__(self, m: Module):
    self.m = m
    # control flow tree
    self.root = Block()
    self.block = self.root # branch we're currently accumulating into
    # assignment accumulators
    self.comb: list[Statement] = []
    self.sync: list[Statement] = []
    self.on_done: list[Statement] = []

  def accumulate(
    self,
    *,
    comb: Iterable[Statement] = (),
    sync: Iterable[Statement] = (),
    on_done: Iterable[Statement] = (),
  ):
    self.comb.extend(comb)
    self.sync.extend(sync)
    self.on_done.extend(on_done)

  def finish_step(self, step: Step):
    comb, self.comb = self.comb, []
    sync, self.sync = self.sync, []
    on_done, self.on_done = self.on_done, []
    self.block.items.append(Assigns(comb, sync, on_done, step.until))

  def If(self, cond: Value) -> FlowIf:
    return FlowIf(self, cond)

  def Elif(self, cond: Value) -> FlowElif:
    return FlowElif(self, cond)

  def Else(self) -> FlowElse:
    return FlowElse(self)

  def While(self, cond: Value) -> FlowWhile:
    return FlowWhile(self, cond)

class Step:
  """Generated by a program step to indicate that, at this point, the program
  may transition into a new FSM state and wait a clock cycle.
  """

  def __init__(self, *, until: Value, out: Value | None):
    self.until = until
    self.out = out

class Block:
  """List of operations to perform during elaboration, which may branch out
  into more conditional blocks.
  """

  def __init__(self):
    self.items: list[Assigns | Branch | Loop] = []

class Assigns:
  """List of assignments to add to `m.d` during elaboration of a state."""

  def __init__(
    self,
    comb: list[Statement],
    sync: list[Statement],
    on_done: list[Statement],
    until: Value,
  ):
    self.comb = comb
    self.sync = sync
    self.on_done = on_done
    self.until = until

class Branch:
  def __init__(self):
    self.arms: list[tuple[Value, Block]] = []
    self.or_else: Block | None = None

class Loop:
  def __init__(self, cond: Value):
    self.cond = cond
    self.body = Block()

# control flow

class FlowIf:
  def __init__(self, flow: Flow, cond: Value):
    self.flow = flow
    self.cond = cond

  def __enter__(self):
    self.parent = self.flow.block

    # make a new branch
    self.branch = Branch()
    self.body = Block()
    self.branch.arms.append((self.cond, self.body))
    self.parent.items.append(self.branch)

    # future accumulations go in this body
    self.flow.block = self.body
    return self

  def __exit__(self, exc_type, exc, traceback):
    self.flow.block = self.parent
    return False

class FlowElif:
  def __init__(self, flow: Flow, cond: Value):
    self.flow = flow
    self.cond = cond

  def __enter__(self):
    self.parent = self.flow.block

    # reuse the last existing branch
    if not self.parent.items:
      raise ValueError("`Elif` requires a preceding `If`/`Elif`")
    branch = self.parent.items[-1]
    if not isinstance(branch, Branch):
      raise TypeError("Preceding item must be a branch")
    if branch.or_else is not None:
      raise ValueError("Cannot add `Elif` after `Else`")
    self.body = Block()
    branch.arms.append((self.cond, self.body))

    # future accumulations go in this body
    self.flow.block = self.body
    return self

  def __exit__(self, exc_type, exc, traceback):
    self.flow.block = self.parent
    return False

class FlowElse:
  def __init__(self, flow: Flow):
    self.flow = flow

  def __enter__(self):
    self.parent = self.flow.block

    # reuse the last existing branch
    if not self.parent.items:
      raise ValueError("`Else` requires a preceding `If`/`Elif`")
    branch = self.parent.items[-1]
    if not isinstance(branch, Branch):
      raise TypeError("Preceding item must be a branch")
    if branch.or_else is not None:
      raise ValueError("Cannot add `Else` after `Else`")
    self.body = Block()
    branch.or_else = self.body

    # future accumulations go in this body
    self.flow.block = self.body
    return self

  def __exit__(self, exc_type, exc, traceback):
    self.flow.block = self.parent
    return False

class FlowWhile:
  def __init__(self, flow: Flow, cond: Value):
    self.flow = flow
    self.cond = cond

  def __enter__(self):
    self.parent = self.flow.block
    self.loop = Loop(self.cond)
    self.parent.items.append(self.loop)

    # future accumulations go in this body
    self.flow.block = self.loop.body
    return self

  def __exit__(self, exc_type, exc, traceback):
    self.flow.block = self.parent
    return False

# expansion

def expand(
  m: Module,
  make_gen: Callable[
    [Flow],
    Generator[
      Step,
      Any, # pyright: ignore[reportExplicitAny]
      None,
    ]
  ],
):
  flow = Flow(m)
  gen = make_gen(flow)
  result = None

  while True:
    try:
      step = gen.send(result)
      flow.finish_step(step)
      result = step.out
    except StopIteration:
      if flow.comb:
        raise ValueError("Uncommitted `comb` effects; did you forget to `yield`?")
      if flow.sync:
        raise ValueError("Uncommitted `sync` effects; did you forget to `yield`?")
      if flow.on_done:
        raise ValueError("Uncommitted `on_done` effects; did you forget to `yield`?")
      break

  class Action:
    def __init__(self, assigns: Assigns, following: Target):
      self.assigns = assigns
      self.following = following

  class Decision:
    def __init__(
      self,
      arms: list[tuple[Value, Target]],
      otherwise: Target,
    ):
      self.arms = arms
      self.otherwise = otherwise

  # None is the end of the program, which loops back to its entry.
  type Target = Action | Decision | None

  def lower(block: Block, after: Target) -> Target:
    entry = after
    for item in reversed(block.items):
      if isinstance(item, Assigns):
        entry = Action(item, entry)
      elif isinstance(item, Loop):
        # The body's continuation is its own condition, not the following item.
        loop = Decision([], entry)
        loop.arms.append((item.cond, lower(item.body, loop)))
        entry = loop
      else:
        otherwise = lower(item.or_else, entry) if item.or_else is not None else entry
        arms = [(cond, lower(body, entry)) for cond, body in item.arms]
        # A branch whose arms all fall through has no work to dispatch.
        if all(target is otherwise for _, target in arms):
          entry = otherwise
        else:
          entry = Decision(arms, otherwise)
    return entry

  entry = lower(flow.root, None)
  if entry is None:
    return

  states: list[Action | Decision] = []
  names: dict[Action | Decision, str] = {}

  def schedule(target: Target) -> str:
    if target is None:
      target = entry
    assert target is not None
    if target not in names:
      names[target] = str(len(states))
      states.append(target)
    return names[target]

  def emit(target: Target, decisions: tuple[Decision, ...] = ()) -> None:
    if target is None:
      target = entry
    assert target is not None

    if isinstance(target, Decision):
      if target in decisions:
        # A path with no yielded action waits here instead of restarting the flow.
        m.next = schedule(target)
        return
      decisions = (*decisions, target)
      for i, (cond, arm) in enumerate(target.arms):
        with m.If(cond) if i == 0 else m.Elif(cond):
          emit(arm, decisions)
      with m.Else():
        emit(target.otherwise, decisions)
      return

    assigns = target.assigns
    m.d.comb += assigns.comb
    m.d.sync += assigns.sync

    # optimization for `Const(True)` and similar
    if isinstance(assigns.until, Const) and assigns.until.value:
      m.d.sync += assigns.on_done
      m.next = schedule(target.following)
    else:
      with m.If(assigns.until):
        m.d.sync += assigns.on_done
        m.next = schedule(target.following)
      with m.Else():
        # Commit to this action instead of reconsidering its branch next cycle.
        m.next = schedule(target)

  first_state = schedule(entry)
  with m.FSM(init=first_state):
    i = 0
    while i < len(states):
      with m.State(str(i)):
        emit(states[i])
      i += 1

# helpers / higher-level API

def step(
  f: Flow,
  *,
  comb: Statement | Iterable[Statement] = (),
  sync: Statement | Iterable[Statement] = (),
  until: Value | None = None,
  on_done: Statement | Iterable[Statement] = (),
  out: Value | None = None,
) -> Step:
  f.accumulate(
    comb=[comb] if isinstance(comb, Statement) else comb,
    sync=[sync] if isinstance(sync, Statement) else sync,
    on_done=[on_done] if isinstance(on_done, Statement) else on_done,
  )
  return Step(
    until=Const(True) if until is None else until,
    out=out,
  )

def sync(f: Flow, assigns: Statement | Iterable[Statement]) -> Step:
  return step(f, sync=assigns)

def comb(f: Flow, assigns: Statement | Iterable[Statement]) -> Step:
  return step(f, comb=assigns)

def tick(f: Flow) -> Step:
  return step(f)
